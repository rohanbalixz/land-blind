"""Render ``results/summary.md`` from ``results/results.json``.

Every number quoted in the README comes from this file, which comes from the run.
"""

from __future__ import annotations

TEST_LABELS = {
    "H1": "β̄ FGN < 0 (truth: HRES-t0)",
    "H2": "Δβ̄ FGN − IFS < 0",
    "H3": "β̄ GenCast < 0 (truth: ERA5)",
    "H4": "Δβ̄ GenCast − IFS < 0",
}


def _ci(d: dict) -> str:
    lo, hi = d["ci95"]
    return f"[{lo:+.3f}, {hi:+.3f}]"


def _p(x: float) -> str:
    return "< 0.001" if x < 0.001 else f"{x:.3f}"


def _row(label: str, d: dict, p_key: str = "p_one_sided") -> str:
    p = d.get(p_key, d.get("p_two_sided", float("nan")))
    return f"| {label} | {d['estimate']:+.3f} | {_ci(d)} | {_p(p)} |"


def render(results: dict) -> str:
    dom = results["domain"]
    lines = [
        "# Results summary",
        "",
        "Generated by `python -m landmem analyze` from `results/results.json`; "
        "do not edit by hand.",
        "",
        f"- Pre-registration commit: `{results['preregistration_commit']}`",
        f"- Code commit: `{results['code_commit']}`",
        f"- Domain: {dom['n_cells']} land cells; {dom['n_water']} water-limited, "
        f"{dom['n_energy']} energy-limited.",
        "",
        "Units: K of afternoon 2 m temperature error per standard deviation of initial root-zone "
        "soil-moisture anomaly, averaged over lead days 3–10. Negative means the forecast is too "
        "cold when soils start dry.",
        "",
        "## Confirmatory tests (Holm-adjusted, one-sided α = 0.05)",
        "",
        "| Test | Estimate | 95% CI | p | Holm p | MDE (80%) | Equivalent within ±0.10 | "
        "Verdict |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for key, t in results["confirmatory"].items():
        lines.append(
            f"| {key}: {TEST_LABELS[key]} | {t['estimate']:+.3f} | {_ci(t)} | "
            f"{_p(t['p_one_sided'])} | {_p(t['p_holm'])} | {t['mde80']:.3f} | "
            f"{'yes' if t['equivalent_within_sesoi'] else 'no'} | **{t['verdict']}** |")
    for name, pr in results["pairs"].items():
        n = pr["sample_primary"]
        lines += ["", f"## {name}", "",
                  f"Primary sample: {n['n_obs']:,} cell-initialisations, {n['n_cells']} cells, "
                  f"{n['n_dates']} dates.", "",
                  "| Quantity | Estimate | 95% CI | p |", "|---|---|---|---|",
                  _row("β̄ AI", pr["primary"]["beta_ai"]),
                  _row("β̄ IFS ENS", pr["primary"]["beta_ifs"]),
                  _row("Δβ̄ (AI − IFS)", pr["primary"]["delta"]),
                  _row("S1 lead growth: Δβ(7–10) − Δβ(1–2)", pr["S1_lead_growth"])]
        if "S2_diurnal" in pr:
            lines.append(_row("S2 afternoon − night Δβ̄", pr["S2_diurnal"]["afternoon_minus_night"]))
        s3 = pr["S3_regime"]
        lines += [_row("S3 Δβ̄ water − energy", s3["delta_water_minus_energy"]),
                  _row("S3 β̄ AI water − energy", s3["beta_ai_water_minus_energy"]),
                  _row("S4 trend of β̄ AI per coupling decile",
                       pr["S4_dose_response"]["trend_per_decile"])]
        s5 = pr["S5_placebo"]
        lines.append(f"| S5 wrong-year placebo (true β̄ AI vs 30 placebo years) | "
                     f"{s5['true']:+.3f} | placebo mean {s5['placebo_mean']:+.3f}, "
                     f"sd {s5['placebo_sd']:.3f} | rank p {s5['rank_p']:.3f} |")
        if "S6_circulation" in pr:
            s6 = pr["S6_circulation"]
            lines += [_row("S6 β AI, lead day 5", s6["beta_day5"]),
                      _row("S6 β AI, lead day 5, with Z500 error control",
                           s6["beta_day5_with_z500_error"]),
                      _row("S6 retained fraction", s6["retained_fraction"], "p_two_sided"),
                      _row("S6 Z500 error slope on s (m per SD)",
                           s6["z500_error_slope_m_per_sd"], "p_two_sided")]
        rob = pr["robustness"]
        lines += ["", "Robustness (β̄ AI, Δβ̄):", "",
                  "| Check | β̄ AI | Δβ̄ |", "|---|---|---|",
                  f"| R1 truth swap | {rob['R1_truth_swap']['beta_ai']['estimate']:+.3f} | "
                  f"(truth-free) |"]
        for key in ("R2_cellmonth+date", "R2_date_only", "R2_no_controls", "R3_block14",
                    "R4_surface_layer"):
            r = rob[key]
            extra = (f" (SE {r['beta_ai']['se_boot']:.3f})" if key == "R3_block14" else "")
            lines.append(f"| {key} | {r['beta_ai']['estimate']:+.3f}{extra} | "
                         f"{r['delta']['estimate']:+.3f} |")
        for cont, r in rob["R5_leave_one_continent_out"].items():
            if "skipped" in r:
                continue
            lines.append(f"| R5 without {cont} ({r['n_cells_dropped']} cells) | "
                         f"{r['beta_ai']:+.3f} | {r['delta']:+.3f} |")
        worst = max(v["abs_error"] for v in rob["R7_injection"].values())
        lines.append(f"| R7 injection recovery, max abs error | {worst:.1e} | |")
        if "exploratory_level_slopes" in pr:
            lines += ["", "Exploratory, not pre-registered: slope of each level on *s* (K per SD, "
                      "lead days 3–10). The error slope is the truth slope minus the forecast "
                      "slope.", "", "| Fixed effects | truth | AI forecast | IFS forecast |",
                      "|---|---|---|---|"]
            for fe, d in pr["exploratory_level_slopes"].items():
                cells = " | ".join(f"{d[k]['mean_3_10']['estimate']:+.3f} {_ci(d[k]['mean_3_10'])}"
                                   for k in ("truth", "ai", "ifs"))
                lines.append(f"| {fe} | {cells} |")
    if "members_fgn2022" in results:
        m = results["members_fgn2022"]
        lines += ["", "## Ensemble members, FGN vs IFS ENS, lead day 5 (2022)", "",
                  "| Quantity | Estimate | 95% CI | p |", "|---|---|---|---|",
                  _row("S7 observed − FGN hot-day probability, dry soils",
                       m["S7_obs_minus_fgn_prob_dry"]),
                  _row("S7 IFS − FGN hot-day probability, dry soils",
                       m["S7_ifs_minus_fgn_prob_dry"]),
                  _row("S8 CRPSS (FGN vs IFS), dry − wet", m["S8_crpss_dry_minus_wet"]),
                  _row("S9 FGN spread–skill ratio, dry − wet", m["S9_ssr_dry_minus_wet"]),
                  "", "| Stratum | n | observed hot freq. | FGN prob. | IFS prob. | CRPS FGN | "
                  "CRPS IFS | SSR FGN |", "|---|---|---|---|---|---|---|---|"]
        for label in ("dry", "wet"):
            z = m[f"strata_{label}"]
            lines.append(f"| {label} | {z['n_obs']:,} | {z['obs_freq']:.3f} | {z['p_fgn']:.3f} | "
                         f"{z['p_ifs']:.3f} | {z['crps_fgn']:.3f} | {z['crps_ifs']:.3f} | "
                         f"{z['ssr_fgn']:.3f} |")
    return "\n".join(lines) + "\n"
